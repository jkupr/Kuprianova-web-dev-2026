-- 1. Создаём базу данных (если ещё не создана)
CREATE DATABASE IF NOT EXISTS friends
    CHARACTER SET utf8mb4
    COLLATE utf8mb4_unicode_ci;

-- 2. Переключаемся на неё
USE friends;

-- 3. Создаём таблицу friends
--    Каждый контакт содержит 9 атрибутов по заданию + числовой id (первичный ключ с автоинкрементом)
CREATE TABLE IF NOT EXISTS friends (
    id          INT          NOT NULL AUTO_INCREMENT PRIMARY KEY,  -- числовой ключ
    surname     VARCHAR(100) NOT NULL,        -- фамилия
    name        VARCHAR(100) NOT NULL,        -- имя
    patronymic  VARCHAR(100) DEFAULT '',      -- отчество
    gender      CHAR(1)      DEFAULT 'М',     -- пол: М или Ж
    birthdate   DATE,                         -- дата рождения
    phone       VARCHAR(30)  DEFAULT '',      -- телефон
    address     VARCHAR(255) DEFAULT '',      -- адрес
    email       VARCHAR(150) DEFAULT '',      -- e-mail
    comment     TEXT         DEFAULT ''       -- комментарий
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

