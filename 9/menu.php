<?php
/**
 * Модуль menu.php
 * Содержит функцию getMenu() без параметров,
 * которая возвращает HTML-код основного меню сайта в виде строки.
 *
 * Согласно заданию:
 * - пункты меню оформлены кнопками-ссылками синего цвета;
 * - активный пункт выделяется красным;
 * - при выборе "Просмотр" появляется подменю сортировки (меньшего размера, того же стиля);
 * - активный пункт подменю также выделяется красным;
 * - при переходе по подменю основной пункт остаётся выделенным.
 */
function getMenu(): string
{
    // Если параметр 'p' не передан — первая загрузка страницы,
    // устанавливаем значение по умолчанию 'viewer'
    if (!isset($_GET['p'])) {
        $_GET['p'] = 'viewer';
    }

    // Проверяем допустимость значения параметра 'p'
    // Если передано недопустимое значение — принудительно останавливаем программу
    $allowedPages = ['viewer', 'add', 'edit', 'delete'];
    if (!in_array($_GET['p'], $allowedPages)) {
        // Недопустимое значение параметра — аналог ошибки 404
        die('<div class="error-msg">Ошибка: недопустимый раздел сайта.</div>');
    }

    $p = $_GET['p']; // текущий активный пункт меню

    // Начинаем формировать HTML-код меню
    $html = '<nav id="menu">';

    // --- Основные пункты меню ---
    // Каждый пункт — ссылка-кнопка; если пункт активен — добавляем класс selected

    // Пункт 1: Просмотр
    $html .= '<a href="?p=viewer" class="menu-btn' . ($p == 'viewer' ? ' selected' : '') . '">Просмотр</a>';

    // Пункт 2: Добавление записи
    $html .= '<a href="?p=add" class="menu-btn' . ($p == 'add' ? ' selected' : '') . '">Добавление записи</a>';

    // Пункт 3: Редактирование записи
    $html .= '<a href="?p=edit" class="menu-btn' . ($p == 'edit' ? ' selected' : '') . '">Редактирование записи</a>';

    // Пункт 4: Удаление записи
    $html .= '<a href="?p=delete" class="menu-btn' . ($p == 'delete' ? ' selected' : '') . '">Удаление записи</a>';

    // --- Подменю сортировки (показывается только при активном пункте "Просмотр") ---
    if ($p == 'viewer') {
        $sort = isset($_GET['sort']) ? $_GET['sort'] : 'byid';

        $html .= '<div id="submenu">';

        // Подпункт 1: По умолчанию (по порядку добавления, т.е. по id)
        $html .= '<a href="?p=viewer&sort=byid" class="submenu-btn' .
            (!isset($_GET['sort']) || $_GET['sort'] == 'byid' ? ' selected' : '') . '">По умолчанию</a>';

        // Подпункт 2: По фамилии
        $html .= '<a href="?p=viewer&sort=fam" class="submenu-btn' .
            (isset($_GET['sort']) && $_GET['sort'] == 'fam' ? ' selected' : '') . '">По фамилии</a>';

        // Подпункт 3: По дате рождения
        $html .= '<a href="?p=viewer&sort=birth" class="submenu-btn' .
            (isset($_GET['sort']) && $_GET['sort'] == 'birth' ? ' selected' : '') . '">По дате рождения</a>';

        $html .= '</div>';
    }

    $html .= '</nav>';

    return $html;
}
